#!/usr/bin/env node
/**
 * Builds the public-release facility dataset.
 *
 * Inputs : data/seed-libraries.json (city/national libraries), data/public-parks.json (parks & gardens)
 * Outputs: supabase/migrations/00014_public_release_dataset.sql
 *          docs/verification-worksheet.csv (only created if missing; pass --reset-worksheet to rebuild)
 *
 * Release rule (INV-001): nothing is published as VERIFIED until a person has confirmed it.
 *  - Place location (name/address/coordinates) -> ESTIMATE, with a note saying where it came from.
 *  - Opening hours, amenities, Green Index      -> not published (shown as "Not available yet").
 *  - Barangay reading centers are held back entirely: their existence is not confirmed yet.
 *
 * Usage: node scripts/data/build-public-release-seed.mjs
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const read = (p) => JSON.parse(readFileSync(resolve(root, p), "utf8"));

const NCR = { minLat: 14.3, maxLat: 14.8, minLng: 120.9, maxLng: 121.2 };
const LOCATION_NOTE =
  "Location compiled from public directory listings and map data; not yet confirmed on site. Please check with the facility before visiting.";

const libSource = read("data/seed-libraries.json");
const details = new Map(libSource.library_details.map((d) => [d.place_id, d]));

const libraries = libSource.places
  .filter((p) => p.category === "library" && !details.get(p.id)?.is_barangay_reading_center)
  .map((p, i) => ({
    id: `ae100000-0000-4000-8000-${String(i + 1).padStart(12, "0")}`,
    name: p.name,
    category: "library",
    description: `Public library in ${p.lgu_city}.`,
    lgu_city: p.lgu_city,
    barangay: p.barangay,
    address: p.address,
    lat: p.coordinates.lat,
    lng: p.coordinates.lng,
  }));

const heldBack = libSource.places.filter((p) => !libraries.some((l) => l.name === p.name));

const parks = read("data/public-parks.json").map((p, i) => ({
  id: `ae200000-0000-4000-8000-${String(i + 1).padStart(12, "0")}`,
  name: p.name,
  category: p.category,
  description: `${p.category === "garden" ? "Public garden" : "Public park"} in ${p.lgu_city}.`,
  lgu_city: p.lgu_city,
  barangay: p.barangay,
  address: p.address,
  lat: p.lat,
  lng: p.lng,
}));

const places = [...libraries, ...parks];

// sanity checks: unique names/ids, coordinates inside Metro Manila
const names = new Set();
for (const p of places) {
  if (names.has(p.name)) throw new Error(`Duplicate place name: ${p.name}`);
  names.add(p.name);
  if (!(p.lat >= NCR.minLat && p.lat <= NCR.maxLat && p.lng >= NCR.minLng && p.lng <= NCR.maxLng)) {
    throw new Error(`Coordinates outside NCR for ${p.name}: ${p.lat},${p.lng}`);
  }
}

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const vid = (placeId) => `af${placeId.slice(2)}`; // one verification row per place (ae… -> af…)

const sql = `-- Migration: 00014_public_release_dataset.sql
-- GENERATED by scripts/data/build-public-release-seed.mjs — edit the inputs and re-run, don't edit by hand.
--
-- Public-release dataset (INV-001 / BR-001):
--   * Earlier seeds were labelled VERIFIED by automated tooling with no human confirmation.
--     They are replaced here. Nothing is VERIFIED until a person confirms it (docs/verification-worksheet.csv).
--   * Location data is published as ESTIMATE with a derivation note. Hours, amenities and Green Index are
--     not published, so clients show "Not available yet".
--   * Barangay reading centers are held back until their existence is confirmed.

BEGIN;

-- 1. Remove the earlier facility seeds (cascades to library_details, operating_hours, green_index_metrics).
DELETE FROM places;

-- 2. No remaining record may claim VERIFIED without a person having confirmed it.
UPDATE verification_meta
   SET status = 'ESTIMATE',
       derivation_note = COALESCE(derivation_note, 'Seeded from compiled public sources by automated tooling; not yet confirmed by a person.'),
       last_verified_at = NULL
 WHERE status = 'VERIFIED';

-- 3. Launch dataset: ${places.length} places (${libraries.length} libraries, ${parks.length} parks & gardens).
INSERT INTO verification_meta (id, status, official_source_name, official_source_url, derivation_note, last_verified_at, verified_by)
VALUES
${places.map((p) => `    (${q(vid(p.id))}, 'ESTIMATE', NULL, NULL, ${q(LOCATION_NOTE)}, NULL, NULL)`).join(",\n")};

INSERT INTO places (id, name, category, description, lgu_city, barangay, address, coordinates, verification_id)
VALUES
${places
  .map(
    (p) =>
      `    (${q(p.id)}, ${q(p.name)}, ${q(p.category)}, ${q(p.description)}, ${q(p.lgu_city)}, ${q(p.barangay)}, ${q(p.address)}, ST_SetSRID(ST_MakePoint(${p.lng}, ${p.lat}), 4326)::geography, ${q(vid(p.id))})`
  )
  .join(",\n")};

-- 4. Read model for the API: plain lat/lng plus the place's verification label.
--    The view runs with the caller's rights, so the public-read RLS policies on the tables still apply.
--    Grants are explicit so this doesn't depend on the platform's default privileges.
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT ON places, verification_meta TO anon, authenticated;
CREATE OR REPLACE VIEW public_places
WITH (security_invoker = true) AS
SELECT
    p.id,
    p.name,
    p.category::text            AS category,
    p.description,
    p.lgu_city,
    p.barangay,
    p.address,
    ST_Y(p.coordinates::geometry) AS lat,
    ST_X(p.coordinates::geometry) AS lng,
    v.status::text              AS verification_status,
    v.official_source_name,
    v.official_source_url,
    v.derivation_note,
    v.last_verified_at
FROM places p
JOIN verification_meta v ON v.id = p.verification_id;

GRANT SELECT ON public_places TO anon, authenticated;

-- 5. Newsletter sign-ups (written only by the API with the service role; never readable by clients).
CREATE TABLE IF NOT EXISTS newsletter_signups (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email TEXT NOT NULL,
    consent_given BOOLEAN NOT NULL,
    consent_text TEXT NOT NULL,
    source TEXT NOT NULL DEFAULT 'landing_footer',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_newsletter_consent CHECK (consent_given = TRUE),
    CONSTRAINT chk_newsletter_email CHECK (email ~* '^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$' AND char_length(email) <= 254)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_newsletter_signups_email ON newsletter_signups (lower(email));
ALTER TABLE newsletter_signups ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON newsletter_signups FROM anon, authenticated;

COMMIT;
`;

writeFileSync(resolve(root, "supabase/migrations/00014_public_release_dataset.sql"), sql);

// Verification worksheet: one row per facility, including the held-back reading centers.
const csv = (v) => `"${String(v ?? "").replace(/"/g, '""')}"`;
const rows = [
  ["place_id", "name", "category", "city", "address", "published", "to_confirm", "confirmed_by", "confirmed_on", "official_source_name", "official_source_url", "notes"],
  ...places.map((p) => [p.id, p.name, p.category, p.lgu_city, p.address, "yes (location as Estimate)", "exists at this address; opening hours; amenities", "", "", "", "", ""]),
  ...heldBack.map((p) => [
    "",
    p.name,
    p.category,
    p.lgu_city,
    p.address,
    "no (held back)",
    "that it exists and is open to the public; address; opening hours; amenities",
    "",
    "",
    "",
    "",
    "",
  ]),
];
// The worksheet is where people record confirmations, so never overwrite it unless asked to.
const worksheetPath = resolve(root, "docs/verification-worksheet.csv");
if (!existsSync(worksheetPath) || process.argv.includes("--reset-worksheet")) {
  writeFileSync(worksheetPath, rows.map((r) => r.map(csv).join(",")).join("\n") + "\n");
}

console.log(`Wrote ${places.length} places (${libraries.length} libraries, ${parks.length} parks/gardens); held back ${heldBack.length}.`);
