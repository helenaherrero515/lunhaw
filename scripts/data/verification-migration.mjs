#!/usr/bin/env node
/**
 * Turns confirmations recorded in docs/verification-worksheet.csv into a new database migration.
 *
 * For every published place (row has a place_id) where a person has filled in
 *   confirmed_by, confirmed_on (YYYY-MM-DD), official_source_name and official_source_url,
 * the place's location label is upgraded from Estimate to VERIFIED with that source and date.
 * Rows with any of those missing are left as they are. Incomplete or invalid rows stop the script.
 *
 * Already-applied migrations can't change, so each run writes a NEW migration file, which
 * `supabase db push` (or the Deploy workflow) then applies.
 *
 * Usage: node scripts/data/verification-migration.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const migrationsDir = resolve(root, "supabase/migrations");

// Minimal RFC 4180 CSV parser (quoted fields, doubled quotes, commas/newlines inside quotes).
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.some((f) => f !== "")) rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows;
  return body.map((r) => Object.fromEntries(header.map((h, i) => [h, (r[i] ?? "").trim()])));
}

const rows = parseCsv(readFileSync(resolve(root, "docs/verification-worksheet.csv"), "utf8"));
const confirmed = [];
const problems = [];

for (const r of rows) {
  const filled = [r.confirmed_by, r.confirmed_on, r.official_source_name, r.official_source_url].filter(Boolean).length;
  if (filled === 0) continue;
  const label = r.name || "(unnamed row)";
  if (!r.place_id) { problems.push(`${label}: not published yet. Held-back places need to be added to the dataset first.`); continue; }
  if (filled < 4) { problems.push(`${label}: fill in all of confirmed_by, confirmed_on, official_source_name and official_source_url.`); continue; }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(r.confirmed_on) || Number.isNaN(Date.parse(r.confirmed_on))) { problems.push(`${label}: confirmed_on must be a date like 2026-11-20.`); continue; }
  if (Date.parse(r.confirmed_on) > Date.now()) { problems.push(`${label}: confirmed_on is in the future.`); continue; }
  if (!/^https:\/\/\S+$/.test(r.official_source_url)) { problems.push(`${label}: official_source_url must be an https:// link.`); continue; }
  confirmed.push(r);
}

if (problems.length) {
  console.error("Fix these worksheet rows first:\n- " + problems.join("\n- "));
  process.exit(1);
}
if (!confirmed.length) {
  console.log("No confirmed rows in docs/verification-worksheet.csv. Nothing to do.");
  process.exit(0);
}

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const next = Math.max(...readdirSync(migrationsDir).map((f) => parseInt(f, 10)).filter(Number.isFinite)) + 1;
const stamp = new Date().toISOString().slice(0, 10).replace(/-/g, "");
const file = `${String(next).padStart(5, "0")}_verify_places_${stamp}.sql`;

const sql = `-- Migration: ${file}
-- GENERATED by scripts/data/verification-migration.mjs from docs/verification-worksheet.csv.
-- Upgrades place locations that a person confirmed from Estimate to VERIFIED (BR-001).

BEGIN;
${confirmed
  .map(
    (r) => `
-- ${r.name}: confirmed by ${r.confirmed_by} on ${r.confirmed_on}
UPDATE verification_meta
   SET status = 'VERIFIED',
       official_source_name = ${q(r.official_source_name)},
       official_source_url = ${q(r.official_source_url)},
       derivation_note = NULL,
       last_verified_at = ${q(r.confirmed_on + "T00:00:00+08:00")},
       verified_by = ${q(r.confirmed_by)}
 WHERE id = (SELECT verification_id FROM places WHERE id = ${q(r.place_id)});`
  )
  .join("\n")}

COMMIT;
`;

writeFileSync(resolve(migrationsDir, file), sql);
console.log(`Wrote supabase/migrations/${file} (${confirmed.length} place${confirmed.length === 1 ? "" : "s"} verified).`);
console.log("Clear those rows' confirmation columns afterwards, or the next run will include them again.");
